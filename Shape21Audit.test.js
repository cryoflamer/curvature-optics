const assert=require('assert');
const bridge=require('./CurvatureInverseOpticsBridge');
const g={Camera:{Trans:p=>p},WinTrans:{TransX:x=>x,TransY:y=>y}};
const physical=[[0,0,0],[10,0,0],[0,10,0]];
const edges=[{a:physical[0],b:physical[1]},{a:physical[0],b:physical[2]}];
const translated=physical.map(p=>({physical:p,apparent:[p[0]+2,p[1]+3,p[2]]}));
const rigid=bridge.compareShape(g,translated,edges);
assert.strictEqual(rigid.points,3);
assert.strictEqual(rigid.edges,2);
assert.ok(rigid.rmsNonRigidPx<1e-10);
assert.ok(rigid.maxLengthChangePercent<1e-10);
assert.ok(rigid.maxTiltChangeDeg<1e-10);
const warped=translated.map((s,i)=>({physical:s.physical,apparent:s.apparent.slice()}));
warped[1].apparent[1]+=2;
const distorted=bridge.compareShape(g,warped,edges);
assert.ok(distorted.rmsNonRigidPx>0.1);
assert.ok(distorted.maxTiltChangeDeg>1);
assert.ok(distorted.maxLengthChangePercent>1);
assert.strictEqual(bridge.compareShape(g,[],edges),null);
console.log('Tower #21 shape: rigid shift and non-rigid deformation PASS');
