'use strict';
const assert=require('assert');
const {clipVisibleFooting}=require('../src/renderers/CurvatureInverseOpticsBridge');
const polygon=[[0,0,0],[2,0,0],[2,2,0],[0,2,0],[0,0,0]];
const all=clipVisibleFooting(polygon,p=>p);
assert.strictEqual(all.partial,false);
assert.strictEqual(all.points.length,4);
const half=clipVisibleFooting(polygon,p=>p[0]>=1?p:null);
assert.strictEqual(half.partial,true);
assert.strictEqual(half.points.length,4);
assert(half.points.every(p=>p[0]>=1-1e-4));
assert.strictEqual(clipVisibleFooting(polygon,()=>null),null);
console.log('OpticalFootingClip: OK');
