#!/usr/bin/env node
'use strict';
// The JSON files are authoritative. Generate one ordinary classic script,
// rather than relying on fetch(file://) or maintaining two hand-authored copies.
const fs=require('node:fs');
const path=require('node:path');
const catalog=require('../src/animation/ModernDemoCatalog');
const directory=path.resolve(__dirname,'../demos/modern');
const output=path.resolve(__dirname,'../src/animation/ModernDemoCatalogData.js');
function build(root=directory){
  const manifest=fs.readFileSync(path.join(root,'catalog.json'),'utf8');
  const assets=Object.create(null);
  catalog.parse(manifest,asset=>{
    const text=fs.readFileSync(path.join(root,asset),'utf8');
    assets[asset]=text;
    return text;
  });
  return '/* Generated by tools/build-modern-demo-catalog.js. Do not edit. */\n'+
    '(function(root){\n  \'use strict\';\n'+
    '  var data='+JSON.stringify({manifest,assets}).replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029')+';\n'+
    '  Object.freeze(data.assets);Object.freeze(data);\n'+
    '  if(typeof module===\'object\'&&module.exports)module.exports=data;\n'+
    '  root.CurvatureModernDemoCatalogData=data;\n'+
    '}(typeof globalThis!==\'undefined\'?globalThis:this));\n';
}
function main(args){
  if(args.length&&!(args.length===1&&args[0]==='--check'))throw Error('Usage: node tools/build-modern-demo-catalog.js [--check]');
  const source=build();
  if(args[0]==='--check'){
    if(!fs.existsSync(output)||fs.readFileSync(output,'utf8')!==source)
      throw Error('Built-in demo catalog data is stale; run node tools/build-modern-demo-catalog.js');
    console.log('Built-in demo catalog data is current.');
  }else{
    fs.writeFileSync(output,source);
    console.log('Generated '+path.relative(process.cwd(),output));
  }
}
if(require.main===module){try{main(process.argv.slice(2));}catch(error){console.error(error.message);process.exitCode=1;}}
module.exports={build};
