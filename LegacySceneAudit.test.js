'use strict';
const assert = require('node:assert/strict');
const audit = require('./LegacySceneAudit');
const adapter = require('./LegacySceneAdapter');
const fs = require('node:fs');
const html = fs.readFileSync('CurvatureApp.html','latin1');
const report = audit.inspectSource(html);
assert(report.used.includes('PolygonOnPlane'));
assert(report.captured.includes('PolygonOnPlane'));
assert(report.missing.includes('SetAlpha'));
assert(report.missing.includes('CircleOnPlane'));
assert.equal(report.complete,false);
assert.equal(report.used.length,report.captured.length+report.missing.length);
const calls=[];
const graph={SetLineAttr(...args){calls.push(['style',...args]);},LineOnPlane(...args){calls.push(['line',...args]);}};
const result=audit.captureFrame(graph,g=>{g.SetLineAttr('black',1);g.LineOnPlane(0,0,1,1);});
assert.equal(result.replayVerified,false);
assert.equal(result.summary.count,2);
assert.deepEqual(result.summary.methods,[{name:'LineOnPlane',count:1},{name:'SetLineAttr',count:1}]);
assert.equal(graph.LineOnPlane instanceof Function,true);
assert.deepEqual(calls,[['style','black',1],['line',0,0,1,1]]);
assert.throws(()=>audit.inspectSource(null),/source text/);
console.log('LegacySceneAudit: passed; graph methods:',report.used.length,'not yet captured:',report.missing.length);
